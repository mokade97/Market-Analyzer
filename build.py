#!/usr/bin/env python3
"""Bundle src/*.js into a single index.html so a missing file can never break the app."""
import re,pathlib
root=pathlib.Path(__file__).parent
html=(root/'src/index.template.html').read_text(encoding='utf-8')
for f in ['screener.js','features.js','lens.js','lensui.js','agents.js','klinecharts.js','klpro.js','tvchart.js','replay.js','backtest.js','watcher.js','flow.js','ledger.js','botui.js','paper.js','help.js']:
    js=(root/'src'/f).read_text(encoding='utf-8')
    html=html.replace(f'<script src="{f}"></script>',f'<script>/* ==== {f} ==== */\n'+js+'\n</script>')
css=(root/'src'/'klpro.css').read_text(encoding='utf-8')
html=html.replace('<link rel="stylesheet" href="klpro.css">','<style>/* ==== klpro.css ==== */\n'+css+'\n</style>')
assert 'klpro.css' not in html.replace('==== klpro.css ====','')
ver=re.search(r"fcalc-(v\d+)",(root/'sw.js').read_text(encoding='utf-8')).group(1)
html=re.sub(r'(<small id="appVer"[^>]*>)v\d+(</small>)',lambda m:m.group(1)+ver+m.group(2),html)
print('app version label ->',ver)
assert '<script src=' not in html, 'unbundled script left'
(root/'index.html').write_text(html,encoding='utf-8')
print('built index.html',len(html))

# ---- also emit a Node-compatible copy of the Lens engine for the 24/7 bot ----
lens=(root/'src'/'lens.js').read_text(encoding='utf-8')
engine=("/* AUTO-GENERATED by build.py from src/lens.js — do not edit. Node shim for the in-app Lens engine. */\n"
 "const window=globalThis;if(!globalThis.localStorage)globalThis.localStorage={getItem:()=>null,setItem:()=>{}};\n"
 +lens+"\nmodule.exports=window.lens;\n")
for out in [root/'bot'/'engine.js', root.parent/'lens-bot'/'engine.js']:
    try:
        out.parent.mkdir(parents=True,exist_ok=True);out.write_text(engine,encoding='utf-8');print('engine ->',out)
    except Exception as e:print('engine skip',out,e)

# export SKILL text for the bot desk
_m=re.search(r"const SKILL_TXT=`(.*?)`;",html,re.S)
if _m:
    for out in [root/'bot'/'skill.txt', root.parent/'lens-bot'/'skill.txt']:
        try: out.write_text(_m.group(1),encoding='utf-8');print('skill ->',out)
        except Exception as e:print('skill skip',out,e)
